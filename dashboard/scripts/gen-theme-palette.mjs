// Generates src/app/theme-palette.css: light-mode and accent overrides of
// Tailwind v4's own colour variables.
//
// The dashboard was written dark-only, with ~3,000 palette classes
// (text-white, bg-slate-900/60, text-emerald-400, …). Rather than rewrite
// every class with dark: variants, light mode redefines the variables those
// classes already resolve to, so each class keeps its *role*:
//   - neutrals invert (text-slate-200 stays "strong text", bg-slate-900 stays
//     "card surface"), and `white` becomes ink so text-white / bg-white/5 /
//     border-white/10 read correctly on a light canvas;
//   - chromatic light stops (100-400) darken so tinted text keeps contrast,
//     dark stops (800-950) lighten so tinted surfaces stay pale.
// Accent choice remaps the indigo family the same way.
//
// Run: node scripts/gen-theme-palette.mjs   (re-run after a Tailwind upgrade)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const theme = readFileSync(join(root, 'node_modules/tailwindcss/theme.css'), 'utf8');

const palette = {};
for (const m of theme.matchAll(/--color-([a-z]+)-(\d{2,3}):\s*([^;]+);/g)) {
  (palette[m[1]] ??= {})[m[2]] = m[3].trim();
}

const STOPS = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];
const NEUTRALS = ['slate', 'gray', 'zinc', 'neutral', 'stone'];
const CHROMATIC = [
  'red', 'orange', 'amber', 'yellow', 'lime', 'green', 'emerald', 'teal', 'cyan',
  'sky', 'blue', 'indigo', 'violet', 'purple', 'fuchsia', 'pink', 'rose',
];

// Light-mode source stop -> the stop (or literal) it should take the value of.
const NEUTRAL_LIGHT = {
  50: '950', 100: '900', 200: '800', 300: '700', 400: '600', 500: '500',
  600: '400', 700: '300', 800: '200', 900: '#ffffff', 950: '#f5f7fc',
};
// 300/400 are the dark theme's text stops, so they take the 800/700 shades:
// the 600 shade reads at only ~3:1 on a light glass surface (fails WCAG AA).
const CHROMATIC_LIGHT = {
  50: '50', 100: '800', 200: '800', 300: '800', 400: '700', 500: '600',
  600: '700', 700: '700', 800: '200', 900: '100', 950: '50',
};

const val = (family, stopOrLiteral) =>
  stopOrLiteral.startsWith('#') ? stopOrLiteral : palette[family][stopOrLiteral];

function block(selector, lines) {
  return `${selector} {\n${lines.map((l) => `  ${l}`).join('\n')}\n}\n`;
}

const ACCENTS = {
  indigo: { family: 'indigo', end: 'violet' },
  teal: { family: 'teal', end: 'cyan' },
  rose: { family: 'rose', end: 'pink' },
  amber: { family: 'amber', end: 'orange' },
  sky: { family: 'sky', end: 'indigo' },
};

let css = `/* GENERATED by scripts/gen-theme-palette.mjs — do not edit by hand. */\n\n`;

// Light mode: every neutral + chromatic family.
const light = [];
for (const f of NEUTRALS) {
  if (!palette[f]) continue;
  for (const s of STOPS) light.push(`--color-${f}-${s}: ${val(f, NEUTRAL_LIGHT[s])};`);
}
for (const f of CHROMATIC) {
  if (!palette[f]) continue;
  for (const s of STOPS) light.push(`--color-${f}-${s}: ${val(f, CHROMATIC_LIGHT[s])};`);
}
light.push('--color-white: #141729;');
css += block('html[data-theme="light"]', light) + '\n';

// Accent gradient end + accent remap of the indigo family.
for (const [name, { family, end }] of Object.entries(ACCENTS)) {
  const darkLines = [`--accent-end: ${palette[end]['500']};`];
  const lightLines = [`--accent-end: ${palette[end]['600']};`];
  if (family !== 'indigo') {
    for (const s of STOPS) {
      darkLines.push(`--color-indigo-${s}: ${palette[family][s]};`);
      lightLines.push(`--color-indigo-${s}: ${val(family, CHROMATIC_LIGHT[s])};`);
    }
  }
  const sel = name === 'indigo' ? 'html:not([data-accent]), html[data-accent="indigo"]' : `html[data-accent="${name}"]`;
  const selLight =
    name === 'indigo'
      ? 'html[data-theme="light"]:not([data-accent]), html[data-theme="light"][data-accent="indigo"]'
      : `html[data-theme="light"][data-accent="${name}"]`;
  css += block(sel, darkLines) + block(selLight, lightLines) + '\n';
}

writeFileSync(join(root, 'src/app/theme-palette.css'), css);
console.log(`wrote src/app/theme-palette.css (${css.length} bytes, ${Object.keys(palette).length} families)`);
